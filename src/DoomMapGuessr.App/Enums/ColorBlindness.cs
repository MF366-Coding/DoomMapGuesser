namespace DoomMapGuessr.Enums
{

    /// <summary>
    /// Supported color blindness settings.
    /// </summary>
    public enum ColorBlindness
    {
    
        /// <summary>
        /// No color blindness.
        /// </summary>
        MaintainColor,

        /// <summary>
        /// Red-blindness.
        /// </summary>
        Protanopia,

        /// <summary>
        /// Green-blindness.
        /// </summary>
        Deuteranopia,

        /// <summary>
        /// Blue-blindness.
        /// </summary>
        Tritanopia,

        /// <summary>
        /// Often associated with
        /// black and white vision.
        /// </summary>
        Monochromacy
    
    }

}
